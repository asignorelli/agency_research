-- PHA-2026-V3 human annotation backend for Supabase (Postgres 15+).
--
-- Paste this whole file into Supabase -> SQL Editor -> New query -> Run.
-- It is safe to run again: it never drops data.
--
-- Design:
--   * Tables live in the private schema `pha_private`, which the public API
--     cannot reach. The website can only call the four `pha_*` functions below.
--   * Every save is a new, append-only row (an "event"). Nothing is updated or
--     deleted, so a first-pass judgment is never overwritten by a later edit.
--   * Each annotator has their own access code (stored salted and hashed).
--     An annotator can read back only their own records. A separate
--     coordinator code is needed to export everyone's records.
--
-- After running this file, create everyone's codes in a new query. The result
-- shows each random code once; copy them (only hashes are stored):
--   select * from pha_private.issue_codes('[["human-alyssa","Alyssa"],["human-tommy","Tommy"]]');
-- Or choose codes yourself (never commit them to git):
--   select pha_private.add_annotator('human-alyssa', 'Alyssa', 'their-access-code');
--   select pha_private.set_coordinator_code('a-long-coordinator-code');

create schema if not exists pha_private;
revoke all on schema pha_private from public, anon, authenticated;

create table if not exists pha_private.annotators (
  rater_identifier text primary key check (rater_identifier ~ '^human-[a-z0-9-]+$'),
  display_name     text not null,
  code_salt        text not null,
  code_hash        text not null,
  active           boolean not null default true,
  created_at       timestamptz not null default now()
);

create table if not exists pha_private.settings (
  key   text primary key,
  value text not null
);

create table if not exists pha_private.events (
  event_id            uuid primary key,          -- generated by the browser; makes retries idempotent
  received_at         timestamptz not null default now(),
  rater_identifier    text not null references pha_private.annotators,
  kind                text not null check (kind in ('main', 'practice')),
  item_id             text not null,
  revision            integer not null check (revision >= 1),
  record              jsonb not null,            -- the schema v1.0 grade object
  notes               jsonb not null default '{}'::jsonb, -- worksheet notes, change reason, client info
  client_started_at   timestamptz,
  client_submitted_at timestamptz,
  unique (rater_identifier, kind, item_id, revision)
);

alter table pha_private.annotators enable row level security;
alter table pha_private.settings   enable row level security;
alter table pha_private.events     enable row level security;

-- Append-only: block edits and deletes, even from the dashboard. A coordinator
-- who truly needs to remove a row must drop this trigger deliberately.
create or replace function pha_private.block_changes() returns trigger
language plpgsql as $$
begin
  raise exception 'pha_private.events is append-only';
end $$;

drop trigger if exists events_append_only on pha_private.events;
create trigger events_append_only before update or delete on pha_private.events
  for each row execute function pha_private.block_changes();

-- ---------------------------------------------------------------------------
-- Private helpers (not callable from the website)
-- ---------------------------------------------------------------------------

create or replace function pha_private.hash_code(p_salt text, p_code text) returns text
language sql immutable set search_path = '' as $$
  select encode(sha256(convert_to(p_salt || ':' || coalesce(p_code, ''), 'UTF8')), 'hex');
$$;

create or replace function pha_private.add_annotator(p_rater text, p_name text, p_code text)
returns text language plpgsql set search_path = '' as $$
declare v_salt text := gen_random_uuid()::text;
begin
  if length(coalesce(p_code, '')) < 6 then
    raise exception 'Use an access code of at least 6 characters';
  end if;
  insert into pha_private.annotators (rater_identifier, display_name, code_salt, code_hash)
  values (p_rater, p_name, v_salt, pha_private.hash_code(v_salt, p_code))
  on conflict (rater_identifier) do update
    set display_name = excluded.display_name, code_salt = excluded.code_salt,
        code_hash = excluded.code_hash, active = true;
  return 'Annotator ' || p_rater || ' is ready';
end $$;

create or replace function pha_private.set_coordinator_code(p_code text)
returns text language plpgsql set search_path = '' as $$
declare v_salt text := gen_random_uuid()::text;
begin
  if length(coalesce(p_code, '')) < 12 then
    raise exception 'Use a coordinator code of at least 12 characters';
  end if;
  insert into pha_private.settings values ('coordinator_salt', v_salt)
    on conflict (key) do update set value = excluded.value;
  insert into pha_private.settings values ('coordinator_hash', pha_private.hash_code(v_salt, p_code))
    on conflict (key) do update set value = excluded.value;
  return 'Coordinator code set';
end $$;

create or replace function pha_private.require_annotator(p_rater text, p_code text)
returns text language plpgsql stable set search_path = '' as $$
declare v_name text;
begin
  select a.display_name into v_name from pha_private.annotators a
   where a.rater_identifier = p_rater and a.active
     and a.code_hash = pha_private.hash_code(a.code_salt, p_code);
  if v_name is null then
    raise exception 'Unknown annotator or wrong access code' using errcode = 'P0001';
  end if;
  return v_name;
end $$;

-- A random, readable code such as 'k7m2-q9xa-4tpw' (48 random bits from gen_random_uuid).
create or replace function pha_private.new_code() returns text
language sql volatile set search_path = '' as $$
  select string_agg(substr(x.h, i, 4), '-' order by i)
    from (select replace(gen_random_uuid()::text, '-', '') as h) x, generate_series(1, 9, 4) i;
$$;

-- Create (or reset) every annotator with a fresh random code, plus a new coordinator
-- code, and show the codes once. Only hashes are stored, so copy them from the result.
--   select * from pha_private.issue_codes('[["human-alyssa","Alyssa"],["human-tommy","Tommy"]]');
create or replace function pha_private.issue_codes(p_annotators jsonb)
returns table (who text, access_code text) language plpgsql set search_path = '' as $$
declare a jsonb; v_code text;
begin
  for a in select value from jsonb_array_elements(p_annotators) loop
    v_code := pha_private.new_code();
    perform pha_private.add_annotator(a->>0, a->>1, v_code);
    who := a->>0; access_code := v_code; return next;
  end loop;
  v_code := pha_private.new_code() || '-' || pha_private.new_code();
  perform pha_private.set_coordinator_code(v_code);
  who := 'coordinator'; access_code := v_code; return next;
end $$;

revoke all on all functions in schema pha_private from public, anon, authenticated;

-- ---------------------------------------------------------------------------
-- Public API used by the website (POST /rest/v1/rpc/<name>)
-- ---------------------------------------------------------------------------

create or replace function public.pha_login(p_rater text, p_code text)
returns jsonb language plpgsql stable security definer set search_path = '' as $$
begin
  return jsonb_build_object('rater_identifier', p_rater,
                            'display_name', pha_private.require_annotator(p_rater, p_code),
                            'server_time', now());
end $$;

create or replace function public.pha_save(
  p_rater text, p_code text, p_event_id uuid, p_kind text, p_item_id text,
  p_record jsonb, p_notes jsonb, p_started timestamptz, p_submitted timestamptz)
returns jsonb language plpgsql volatile security definer set search_path = '' as $$
declare
  v_existing pha_private.events;
  v_revision integer;
  v_received timestamptz;
begin
  perform pha_private.require_annotator(p_rater, p_code);

  -- A retry of a save that already reached the server returns the original result.
  select * into v_existing from pha_private.events e where e.event_id = p_event_id;
  if found then
    if v_existing.rater_identifier <> p_rater then
      raise exception 'Event belongs to another annotator';
    end if;
    return jsonb_build_object('revision', v_existing.revision,
                              'received_at', v_existing.received_at, 'duplicate', true);
  end if;

  if p_kind not in ('main', 'practice') then raise exception 'Unknown kind'; end if;
  if jsonb_typeof(p_record) <> 'object' or octet_length(p_record::text) > 60000
     or octet_length(coalesce(p_notes, '{}'::jsonb)::text) > 20000 then
    raise exception 'Record is not a JSON object or is too large';
  end if;
  if p_record->>'blind_id' is distinct from p_item_id
     or p_record->>'rater_identifier' is distinct from p_rater
     or p_record->>'rater_type' is distinct from 'human' then
    raise exception 'Record identity does not match the annotator or item';
  end if;
  if (p_kind = 'main' and p_item_id !~ '^BLIND-[0-9A-F]{12}$')
     or (p_kind = 'practice' and p_item_id !~ '^PRACTICE-C[0-9]{2}$') then
    raise exception 'Unexpected item identifier';
  end if;

  -- Serialize saves of the same item by the same person so revisions stay gapless.
  perform pg_advisory_xact_lock(hashtext(p_rater || '|' || p_kind || '|' || p_item_id));
  select coalesce(max(e.revision), 0) + 1 into v_revision from pha_private.events e
   where e.rater_identifier = p_rater and e.kind = p_kind and e.item_id = p_item_id;

  insert into pha_private.events (event_id, rater_identifier, kind, item_id, revision,
                                  record, notes, client_started_at, client_submitted_at)
  values (p_event_id, p_rater, p_kind, p_item_id, v_revision, p_record,
          coalesce(p_notes, '{}'::jsonb), p_started, p_submitted)
  returning received_at into v_received;

  return jsonb_build_object('revision', v_revision, 'received_at', v_received, 'duplicate', false);
end $$;

-- The annotator's own latest record per item, plus how many saves it has.
create or replace function public.pha_my_records(p_rater text, p_code text)
returns jsonb language plpgsql stable security definer set search_path = '' as $$
declare v_result jsonb;
begin
  perform pha_private.require_annotator(p_rater, p_code);
  select coalesce(jsonb_agg(to_jsonb(t) order by t.kind, t.item_id), '[]'::jsonb) into v_result
  from (
    select distinct on (e.kind, e.item_id)
           e.kind, e.item_id, e.revision, e.record, e.notes, e.received_at, e.event_id,
           e.client_started_at, e.client_submitted_at,
           count(*) over (partition by e.kind, e.item_id) as saves
      from pha_private.events e
     where e.rater_identifier = p_rater
     order by e.kind, e.item_id, e.revision desc
  ) t;
  return v_result;
end $$;

-- Every event from every annotator, for the coordinator's export script.
create or replace function public.pha_export(p_coordinator_code text)
returns jsonb language plpgsql stable security definer set search_path = '' as $$
declare
  v_salt text; v_hash text; v_result jsonb;
begin
  select value into v_salt from pha_private.settings where key = 'coordinator_salt';
  select value into v_hash from pha_private.settings where key = 'coordinator_hash';
  if v_hash is null or v_hash <> pha_private.hash_code(v_salt, p_coordinator_code) then
    raise exception 'Wrong coordinator code' using errcode = 'P0001';
  end if;
  select coalesce(jsonb_agg(to_jsonb(e) order by e.rater_identifier, e.kind, e.item_id, e.revision),
                  '[]'::jsonb) into v_result
    from pha_private.events e;
  return v_result;
end $$;

